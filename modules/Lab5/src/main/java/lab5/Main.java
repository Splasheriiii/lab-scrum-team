package lab5;
import java.util.Random;

public class Main {

    public static void main(String[] args) {

        // =========================
        // ИСХОДНЫЕ ДАННЫЕ ВАРИАНТА 4
        // =========================

        // Число зарегистрированных отказов программы
        int Q = Integer.parseInt(args[0]); //8

        // Общее число проведённых экспериментов
        int N = Integer.parseInt(args[1]); //1400

        // Минимальное время восстановления, с
        double TV_MIN = Double.parseDouble(args[2]); //0.5

        // Максимальное время восстановления, с
        double TV_MAX = Double.parseDouble(args[3]); //1.3

        // Количество значений в выборке времени восстановления
        int TV_SAMPLE_SIZE = Integer.parseInt(args[4]); //100

        // Допустимое время восстановления, с
        double TV_ALLOWED = Double.parseDouble(args[5]); //0.75;

        // Минимальное время преобразования входного набора данных, с
        double TP_MIN = Double.parseDouble(args[6]);//6.0;

        // Максимальное время преобразования входного набора данных, с
        double TP_MAX = Double.parseDouble(args[7]);//10.0;

        // Количество значений в выборке времени преобразования
        int TP_SAMPLE_SIZE = Integer.parseInt(args[8]);//200;

        // Допустимое время преобразования входного набора данных, с
        double TP_ALLOWED = Double.parseDouble(args[9]);//16.0;

        // Базовое значение критерия надёжности,
        // с которым сравнивается рассчитанный абсолютный показатель
        double BASE_CRITERION = Double.parseDouble(args[10]);//0.96;

        // Фиксированное начальное значение генератора случайных чисел.
        // Благодаря этому при каждом запуске программа создаёт
        // одну и ту же последовательность случайных значений.
        // Это делает результаты расчёта воспроизводимыми.
        long RANDOM_SEED = Long.parseLong(args[11]);//895L;

        // Создаём генератор случайных чисел
        Random random = new Random(RANDOM_SEED);


        // =========================
        // 1. ФОРМИРОВАНИЕ ВЫБОРОК
        // =========================

        // Формируем выборку из 100 значений времени восстановления
        // в диапазоне от 0.5 до 1.3 секунды
        double[] recoveryTimes = generateUniformSample(
                random,
                TV_SAMPLE_SIZE,
                TV_MIN,
                TV_MAX
        );

        // Формируем выборку из 200 значений времени преобразования
        // в диапазоне от 6 до 10 секунд
        double[] processingTimes = generateUniformSample(
                random,
                TP_SAMPLE_SIZE,
                TP_MIN,
                TP_MAX
        );


        // =========================
        // 2. РАСЧЁТ Н0401
        // =========================

        // Н0401 характеризует вероятность безотказной работы.
        // Формула:
        // Н0401 = 1 - Q / N
        double h0401 = calculateH0401(Q, N);


        // =========================
        // 3. РАСЧЁТ Н0501
        // =========================

        // Вычисляем среднее время восстановления
        // по выборке из 100 значений
        double averageRecoveryTime = average(recoveryTimes);

        // Рассчитываем оценочный элемент Н0501.
        // Он сравнивает фактическое среднее время восстановления
        // с допустимым временем восстановления.
        double h0501 = calculateH0501(
                averageRecoveryTime,
                TV_ALLOWED
        );


        // =========================
        // 4. РАСЧЁТ Н0502
        // =========================

        // Рассчитываем оценочный элемент Н0502.
        // Для каждого значения времени преобразования проверяется,
        // превышает ли оно допустимое значение.
        double h0502 = calculateH0502(
                processingTimes,
                TP_ALLOWED
        );


        // =========================
        // 5. РАСЧЁТ МЕТРИК
        // =========================

        // Метрика 4 содержит только один оценочный элемент Н0401,
        // поэтому её значение равно Н0401
        double metric4 = h0401;

        // Метрика 5 содержит два оценочных элемента:
        // Н0501 и Н0502.
        // Так как их веса одинаковые, берём среднее арифметическое.
        double metric5 = (h0501 + h0502) / 2.0;


        // =========================
        // 6. АБСОЛЮТНЫЙ ПОКАЗАТЕЛЬ КРИТЕРИЯ
        // =========================

        // В критерий "Работоспособность" входят две метрики.
        // По условию лабораторной их веса одинаковые.
        // Поэтому вес каждой метрики равен 0.5.
        double v4 = 0.5;
        double v5 = 0.5;

        // Рассчитываем абсолютный показатель критерия
        // как взвешенную сумму двух метрик
        double absoluteCriterion =
                metric4 * v4 +
                        metric5 * v5;


        // =========================
        // 7. ОТНОСИТЕЛЬНЫЙ ПОКАЗАТЕЛЬ КРИТЕРИЯ
        // =========================

        // Сравниваем рассчитанный абсолютный показатель
        // с базовым значением критерия 0.96
        double relativeCriterion =
                absoluteCriterion / BASE_CRITERION;


        // =========================
        // 8. ФАКТОР НАДЁЖНОСТИ
        // =========================

        // Для данного класса программ используется только
        // один критерий — "Работоспособность".
        // Поэтому его вес равен 1.
        double criterionWeight = 1.0;

        // Итоговый фактор надёжности равен
        // относительному показателю критерия,
        // умноженному на его вес
        double reliabilityFactor =
                relativeCriterion * criterionWeight;


        // =========================
        // 9. ВЫВОД РЕЗУЛЬТАТОВ
        // =========================

        System.out.println("Лабораторная работа №5");
        System.out.println("Вариант 4");
        System.out.println();

        // Вывод среднего времени восстановления
        System.out.printf(
                "Среднее время восстановления Tv = %.6f с%n",
                averageRecoveryTime
        );

        // Вывод оценочного элемента Н0401
        System.out.printf(
                "Н0401 = %.6f%n",
                h0401
        );

        // Вывод оценочного элемента Н0501
        System.out.printf(
                "Н0501 = %.6f%n",
                h0501
        );

        // Вывод оценочного элемента Н0502
        System.out.printf(
                "Н0502 = %.6f%n",
                h0502
        );

        System.out.println();

        // Вывод значения метрики 4
        System.out.printf(
                "Метрика M4 = %.6f%n",
                metric4
        );

        // Вывод значения метрики 5
        System.out.printf(
                "Метрика M5 = %.6f%n",
                metric5
        );

        System.out.println();

        // Вывод абсолютного показателя критерия
        System.out.printf(
                "Абсолютный показатель критерия P = %.6f%n",
                absoluteCriterion
        );

        // Вывод относительного показателя критерия
        System.out.printf(
                "Относительный показатель критерия K = %.6f%n",
                relativeCriterion
        );

        // Вывод итогового фактора надёжности
        System.out.printf(
                "Фактор надёжности R = %.6f%n",
                reliabilityFactor
        );

        System.out.println();

        // Итоговый результат с округлением до четырёх знаков
        System.out.printf(
                "Итог: R = %.4f%n",
                reliabilityFactor
        );
    }


    // =========================
    // ГЕНЕРАЦИЯ СЛУЧАЙНОЙ ВЫБОРКИ
    // =========================

    public static double[] generateUniformSample(
            Random random,
            int size,
            double min,
            double max) {

        // Создаём массив нужного размера
        double[] sample = new double[size];

        // Заполняем каждый элемент массива случайным значением
        for (int i = 0; i < size; i++) {

            // random.nextDouble() возвращает число от 0 до 1.
            // Умножением и сложением переводим его
            // в диапазон от min до max.
            sample[i] =
                    min +
                            (max - min) *
                                    random.nextDouble();
        }

        // Возвращаем сформированную выборку
        return sample;
    }


    // =========================
    // РАСЧЁТ СРЕДНЕГО ЗНАЧЕНИЯ
    // =========================

    public static double average(double[] values) {

        // Переменная для суммы всех элементов
        double sum = 0.0;

        // Складываем все значения массива
        for (double value : values) {
            sum += value;
        }

        // Делим сумму на количество элементов
        // и получаем среднее арифметическое
        return sum / values.length;
    }


    // =========================
    // РАСЧЁТ Н0401
    // =========================

    public static double calculateH0401(
            int q,
            int n) {

        // Вероятность безотказной работы:
        // Н0401 = 1 - Q / N
        //
        // Приведение q к double нужно,
        // чтобы деление выполнялось как вещественное,
        // а не целочисленное.
        return 1.0 - (double) q / n;
    }


    // =========================
    // РАСЧЁТ Н0501
    // =========================

    public static double calculateH0501(
            double averageRecoveryTime,
            double allowedRecoveryTime) {

        // Если фактическое среднее время восстановления
        // не превышает допустимое,
        // оценочный элемент принимает максимальное значение 1
        if (averageRecoveryTime <= allowedRecoveryTime) {
            return 1.0;
        }

        // Если допустимое время превышено,
        // рассчитывается отношение допустимого времени
        // к фактическому среднему времени восстановления
        return allowedRecoveryTime
                / averageRecoveryTime;
    }


    // =========================
    // РАСЧЁТ Н0502
    // =========================

    public static double calculateH0502(
            double[] processingTimes,
            double allowedProcessingTime) {

        // Здесь будет накапливаться сумма
        // оценок всех элементов выборки
        double sum = 0.0;

        // Перебираем все фактические значения
        // времени преобразования
        for (double actualTime : processingTimes) {

            // Переменная для оценки текущего элемента выборки
            double value;

            // Если время преобразования
            // не превышает допустимое значение,
            // оценка равна 1
            if (actualTime <= allowedProcessingTime) {

                value = 1.0;

            } else {

                // Если допустимое время превышено,
                // рассчитываем отношение допустимого времени
                // к фактическому
                value =
                        allowedProcessingTime
                                / actualTime;
            }

            // Добавляем результат к общей сумме
            sum += value;
        }

        // Усредняем оценки всех элементов выборки
        // и получаем итоговое значение Н0502
        return sum / processingTimes.length;
    }
}